def num(x: float) -> str:
    """Three significant figures, for measures whose scale differs by orders of magnitude."""
    return "" if pd.isna(x) else f"{x:.3g}"


def ordinal(n: float) -> str:
    n = int(n)
    return f"{n}{'th' if 10 <= n % 100 <= 20 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"


def _value(c: Comparison, x: float) -> str:
    return pct(x) if c.measure.key == "net" else num(x)


def _dates(values) -> str:
    return ", ".join(f"{t:%Y-%m-%d}" for t in values) if len(values) else "none"


def drift_chart(d: Drift, path: Path) -> None:
    """Cumulative live net return inside the backtest's band, above the daily slope inside its range."""
    days = d.live_book.index
    fig, (top, bottom) = plt.subplots(2, 1, figsize=(10, 6.5), sharex=True, gridspec_kw={"height_ratios": [1.4, 1]})
    band = d.pnl_band.to_numpy() * PCT
    top.fill_between(days, band[:, 0], band[:, 1], color="tab:blue", alpha=0.15, lw=0, label="backtest, 1st to 99th percentile")
    top.plot(days, d.live_book["net"].cumsum() * PCT, color="black", lw=1.2, marker="o", ms=3, label="live")
    top.axhline(0, color="grey", lw=0.5)
    top.set_ylabel("cumulative net return on capital, %")
    top.set_title(f"Forward run to {d.last.date()}: net return and calibration slope")
    top.legend(fontsize=8, loc="upper left")
    s = d.live_signal["slope"]
    bottom.axhspan(*d.slope_band, color="tab:blue", alpha=0.15, lw=0, label="backtest, 5th to 95th percentile of days")
    bottom.plot(days, s, color="black", lw=1, marker="o", ms=3, label="live")
    neg = (s < 0).to_numpy()
    bottom.scatter(days[neg], s[neg], color="tab:red", s=14, zorder=3, label="negative")
    bottom.axhline(0, color="grey", lw=0.5)
    bottom.set_ylabel("calibration slope")
    bottom.legend(fontsize=8, loc="best")
    fig.autofmt_xdate()
    fig.tight_layout()
    save_figure(fig, path)


def _verdicts(d: Drift) -> list[str]:
    by_group: dict[str, list[Comparison]] = {}
    for c in d.comparisons:
        by_group.setdefault(c.measure.group, []).append(c)

    def state(cs: list[Comparison], what: str) -> str:
        if any(c.verdict == "no data" for c in cs):
            return "not yet measurable (" + ", ".join(c.measure.label for c in cs if c.verdict == "no data") + ")"
        outside = [f"{c.measure.label} {c.verdict} its {what}" for c in cs if c.verdict != "within"]
        return f"within the backtest's {what}" if not outside else "outside: " + "; ".join(outside)

    core = by_group["turnover"] + by_group["signal"] + by_group["IC"]
    return [
        f"- Turnover, signal distributions and IC: {state(core, 'range')}.",
        f"- P&L: {state(by_group['P&L'], 'wide band')}.",
        f"- Gross exposure and the calibration slope, for context: {state(by_group['book'] + by_group['slope'], 'range')}.",
    ]


def _comparison_table(d: Drift) -> str:
    rows = []
    for c in d.comparisons:
        low, high = c.measure.band
        rows.append(
            {
                "measure": c.measure.label,
                "statistic": c.measure.stat,
                "days": c.days,
                "live": _value(c, c.live),
                "reference range": f"{_value(c, c.low)} to {_value(c, c.high)} ({ordinal(low)} to {ordinal(high)})",
                "percentile": fmt(c.percentile, 0),
                "verdict": c.verdict,
            }
        )
    return table(pd.DataFrame(rows))


def _days_table(d: Drift) -> str:
    days = d.live_book.join(d.live_signal)
    rows = [
        {
            "date": f"{t:%Y-%m-%d}",
            "turnover": fmt(r["turnover"], 3),
            "exposure": fmt(r["exposure"], 2),
            "net %": pct(r["net"], 3),
            "slope": num(r["slope"]),
            "IC": fmt(r["ic"], 3),
            "signal sd": num(r["signal_sd"]),
            "expected move sd": num(r["forecast_sd"]),
        }
        for t, r in days.iterrows()
    ]
    return table(pd.DataFrame(rows))


def _revision_lines(d: Drift, shown: int) -> list[str]:
    out = ["## Data revisions\n", "### Each snapshot against the one before\n"]
    if not d.bars:
        out.append("No daily snapshot yet besides the pinned one.\n")
    else:
        rows = [
            {"snapshot": new, "against": old, "tickers changed": len(ch), "of which a new split": int(ch["split"].sum()) if len(ch) else 0}
            for old, new, ch in d.bars
        ]
        out.append(table(pd.DataFrame(rows)))
        parts = [ch.assign(snapshot=new) for _, new, ch in d.bars if len(ch)]
        if parts:
            changes = pd.concat(parts, ignore_index=True)
            top = changes.sort_values("max_price_change", ascending=False, na_position="last").head(shown)
            out.append(f"\nThe {len(top)} largest of {len(changes)} changes, by the largest relative change in a price:\n")
            out.append(
                table(
                    pd.DataFrame(
                        {
                            "snapshot": top["snapshot"],
                            "ticker": top["ticker"],
                            "rows": top["rows"],
                            "fields": top["fields"],
                            "from": top["first"].dt.strftime("%Y-%m-%d"),
                            "to": top["last"].dt.strftime("%Y-%m-%d"),
                            "largest price change %": [pct(x, 4) for x in top["max_price_change"]],
                            "new split": top["split"].map({True: "yes", False: ""}),
                        }
                    )
                )
            )
        out.append("")
    out.append("### Decisions rebuilt from the latest snapshot\n")
    dc = d.decisions
    changed = dc.loc[(dc["target_names"] > 0) | (dc["move_names"] > 0)]
    out.append(
        f"Every ledger day's decision rebuilt from snapshot {d.snapshot} and compared with the one recorded: "
        f"{len(dc) - len(changed)} of {len(dc)} days are identical."
        + (" No revision so far would have changed a decision.\n" if changed.empty else " The days that differ:\n")
    )
    if len(changed):
        out.append(
            table(
                pd.DataFrame(
                    {
                        "date": changed["date"].dt.strftime("%Y-%m-%d"),
                        "names, target": changed["target_names"],
                        "largest target change": [num(x) for x in changed["target_max"]],
                        "names, expected move": changed["move_names"],
                        "largest move change": [num(x) for x in changed["move_max"]],
                    }
                )
            )
        )
        out.append("")
    return out


def _minutes(seconds: float) -> str:
    return f"{seconds / 60:.1f} min"


def _cost_line(r: dict) -> str:
    if not r["timed"]:
        return "- Run time and peak memory: not recorded by any run yet."
    longest, peak = r["longest"], r["peak"]
    return (
        f"- Run time over the {r['timed']} runs that recorded it: median {_minutes(r['median_seconds'])}, longest "
        f"{_minutes(longest['duration_seconds'])} (as of {longest.get('as_of', '')}). Highest peak memory: "
        f"{peak['peak_memory_mb'] / 1024:.1f} GiB (as of {peak.get('as_of', '')})."
    )


def _operations_lines(d: Drift, shown: int) -> list[str]:
    r = d.runs
    failures = r["backup_failures"]
    missing = ", ".join(f"{t:%Y-%m-%d} ({int(v)})" for t, v in d.missing_returns.items()) if len(d.missing_returns) else "none"
    failed = "; ".join(f"{k}: {', '.join(v)}" for k, v in d.source_failed.items()) if d.source_failed else "none"
    out = [
        "## Operations\n",
        f"- Runs logged: {r['runs']} (" + ", ".join(f"{k} {v}" for k, v in sorted(r["by_status"].items())) + ").",
        f"- Ledger backup failures: {len(failures)}" + (f", the last: {failures[-1]['backup']}." if failures else "."),
        _cost_line(r),
        f"- Sessions due and not yet in the ledger: {_dates(d.lagging)}.",
        f"- Days with held names that had no return (booked as zero): {missing}.",
        f"- Tickers the source failed to return: {failed}.",
        f"- Frozen config hashes in the ledger: {', '.join(f'`{h}`' for h in d.config_hashes)}.",
        f"- Days run with uncommitted changes: {_dates(d.dirty_days)}.",
    ]
    if r["trouble"]:
        out.append(f"\nRuns that did not finish cleanly, the last {min(shown, len(r['trouble']))}:\n")
        rows = [{"as of": x.get("as_of", ""), "status": x["status"], "message": x.get("message", "")} for x in r["trouble"][-shown:]]
        out.append(table(pd.DataFrame(rows)))
    out.append("")
    return out


def write_drift_report(d: Drift, out_dir: Path) -> Path:
    """`<last ledger day>.md` and its chart in `out_dir`; a rerun for the same day rewrites both."""
    from statarb.paper.drift import SHOWN

    out_dir.mkdir(parents=True, exist_ok=True)
    name = f"{d.last:%Y-%m-%d}"
    n = len(d.live_book)
    lo, hi = d.reference_span
    chart = f"{name}.png"
    drift_chart(d, out_dir / chart)
    out = [
        f"# Drift report: forward run to {name}\n",
        (
            f"Generated by `uv run python -m statarb.paper.drift`. The forward run from {d.first.date()} to {d.last.date()}: {n} "
            f"sessions in the ledger. Reference: the frozen path, log entry `{d.entry}`, from {lo.date()} to {hi.date()} on the "
            f"reference tables. Live signal, expected move, slope and IC are rebuilt on the tables of snapshot {d.snapshot}. Each live "
            "measure is a statistic over the run's days, compared with the same statistic over every window of as many days in the "
            "reference: within range is the 5th to 95th percentile of those windows, and the P&L band the 1st to 99th. Turnover "
            f"and gross exposure leave out the first {d.ramp_up} sessions, while the book fills from flat.\n"
        ),
        "## Verdict\n",
        *_verdicts(d),
        f"\nWith {n} days, a window statistic is noisy; read a single measure outside its range as a question, not a failure.\n",
        "## Live against the backtest\n",
        _comparison_table(d),
        (
            "\nNet return in per cent of capital; turnover and exposure as fractions of capital; percentile is the share of "
            "reference windows below the live value.\n"
        ),
        f"![Net return and calibration slope]({chart})\n",
        "## Each day\n",
        _days_table(d),
        "\nThe last day has no IC until the next session's residual is known.\n",
        *_revision_lines(d, SHOWN),
        *_operations_lines(d, SHOWN),
    ]
    path = out_dir / f"{name}.md"
    path.write_text("\n".join(out))
    return path
