def slope_chart(name: str, s: np.ndarray, outcomes: list[Outcome], dates: pd.DatetimeIndex, start: int, boundary: int, path: Path) -> None:
    """The trailing slope, negative stretches shaded, above the cumulative gross P&L of the decile sort and the zone."""
    fig, (top, bottom) = plt.subplots(2, 1, figsize=(10, 6.5), sharex=True, gridspec_kw={"height_ratios": [1, 1.4]})
    x, y = dates[start:], s[start:]
    top.plot(x, y, lw=0.8, color="black")
    top.fill_between(x, y, 0, where=np.nan_to_num(y) < 0, color="tab:red", alpha=0.35, lw=0, label="slope below zero")
    top.axhline(0, color="grey", lw=0.5)
    top.set_ylabel("calibration slope")
    top.set_title(f"{name}: trailing calibration slope and gross P&L")
    top.legend(fontsize=8, loc="upper left")
    mine = [o for o in outcomes if o.forecast == name]
    for o in mine:
        if o.rule == DECILE and o.book != mine[0].book:
            continue                     # the decile sort's gross return per dollar of capital is the same at every book size
        what = o.label if o.rule == DECILE else f"{o.label}, {money(o.book)}"
        bottom.plot(o.daily.index, o.daily["gross"].cumsum() * PCT, lw=1, label=what)
    bottom.axhline(0, color="grey", lw=0.5)
    bottom.set_ylabel("cumulative gross return on capital, %")
    bottom.legend(fontsize=8, loc="upper left")
    if boundary < len(dates):
        for ax in (top, bottom):
            ax.axvline(dates[boundary], color="tab:blue", lw=0.8, ls="--")
        bottom.annotate("holdout", (dates[boundary], 0), xytext=(4, 4), textcoords="offset points", fontsize=8, color="tab:blue")
    fig.tight_layout()
    save_figure(fig, path)
    plt.close(fig)


def decile_chart(profile: pd.DataFrame, horizon: int, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(8, 4))
    names = ordered(profile["forecast"])
    buckets = int(profile["decile"].max())
    width = 0.8 / len(names)
    for k, name in enumerate(names):
        g = profile.loc[profile["forecast"] == name]
        ax.bar(g["decile"] + k * width - 0.4 + width / 2, g["mean"] * PCT, width, label=name)
    ax.axhline(0, color="grey", lw=0.5)
    ax.set_xticks(range(1, buckets + 1))
    ax.set_xlabel(f"forecast decile within the day ({buckets} = highest)")
    ax.set_ylabel(f"mean realised {horizon}-day residual move, %")
    ax.set_title("Realised move by forecast decile, development")
    ax.legend(fontsize=8)
    fig.tight_layout()
    save_figure(fig, path)
    plt.close(fig)


def write_choice_report(c: Choice, log: list[dict], out_dir: Path) -> str:
    from statarb.paper.choice import key

    dates = c.full.lab.tables.dates
    ddates = c.dev.lab.tables.dates
    dev_first, dev_last = ddates[c.rf.start], ddates[-1]
    h = c.dev.pc.optimiser.horizon_days
    in_holdout = c.boundary < len(dates)
    out_dir.mkdir(parents=True, exist_ok=True)
    out: list[str] = []
    add = out.append

    add("# Phase 6: evidence for the choice\n")
    add(
        "Generated by `uv run python -m statarb.paper.choice` from `config/paper.toml`, with phase 5's forecasts and portfolio "
        f"rules unchanged. The {c.checked} phase 5 models were retrained and each matched the SHA-256 phase 5 logged. The "
        "evidence the forward run's decision record cites when it chooses the strategy ([brief](../../docs/phases/phase-06/brief.md#evidence-for-the-choice)). "
        f"Fills at the {FILLS[c.dev.pc.run.fill]}; headline cost model; returns per dollar of capital.\n"
    )

    add("## Calibration slope over time\n")
    add(
        f"The trailing {h}-day calibration slope of each forecast (the phase 3 rule), from {dates[c.full_fc.start].date()} to "
        f"{dates[-1].date()}, above the cumulative gross P&L of the decile sort and the no-trade zone on the same forecast. These "
        "paths start flat on the first date"
        + (" and run through the holdout, which phase 5 has read: they describe, and nothing is chosen from them.\n" if in_holdout else ".\n")
    )
    for name in c.full_fc.names:
        file = f"slope_{slug(name)}.png"
        slope_chart(name, c.full_slopes[name], c.diagnostic, dates, c.full_fc.start, c.boundary, out_dir / file)
        add(f"![{name}: slope and gross P&L]({file})\n")
    add("### Share of days with a negative slope\n")
    sh = c.negative_share.pivot(index="year", columns="forecast", values="negative").reindex(columns=c.full_fc.names)
    add(table(sh.reset_index().map(lambda x: x if isinstance(x, str) else pct(x, 0))))
    add("\nPer cent of trading days in each calendar year" + (", the holdout as one period.\n" if in_holdout else ".\n"))
    add("### Gross return by the sign of the slope\n")
    add(
        "Gross return a year on days whose decision-day slope was negative or not, and the capital deployed on those days. The "
        "decile sort ignores the slope; the zone stops opening positions when it is negative.\n"
    )
    rows = [
        {
            "forecast": r["forecast"], "rule": r["rule"], "book": money(r["book"]), "period": r["period"],
            "negative days": r["negative_days"],
            "gross %, slope negative": pct(r["gross_negative"]), "gross %, slope positive": pct(r["gross_positive"]),
            "capital, negative": fmt(r["capital_negative"], 2), "capital, positive": fmt(r["capital_positive"], 2),
        }
        for _, r in c.by_sign.iterrows()
    ]
    add(table(pd.DataFrame(rows)))
    add("")

    add("## Realised move by forecast decile\n")
    add(
        f"Development only, {dev_first.date()} to {dev_last.date()}: the mean realised {h}-day residual move in each decile of "
        "each forecast within the day, over the member-days every forecast covers. A decile book earns the gap between the "
        "outer deciles; a calibrated forecast earns in proportion to the move.\n"
    )
    p = c.profile.pivot(index="decile", columns="forecast", values="mean").reindex(columns=ordered(c.profile["forecast"]))
    top, bottom = int(p.index.max()), int(p.index.min())
    rows = [{"decile": int(d), **{col: fmt(p.loc[d, col] * PCT, 3) for col in p.columns}} for d in p.index]
    rows.append({"decile": f"{top} minus {bottom}", **{col: fmt((p.loc[top, col] - p.loc[bottom, col]) * PCT, 3) for col in p.columns}})
    add(table(pd.DataFrame(rows)))
    add(f"\nMean realised {h}-day residual move, %.\n")
    decile_chart(c.profile, h, out_dir / "decile_profile.png")
    add("![Realised move by forecast decile](decile_profile.png)\n")

    add("## IC by fill timing\n")
    add(
        "Development only, on the member-days every forecast covers: the mean daily rank IC of each forecast on *t* against total "
        "returns over each window. Phase 5 measures IC from the close of *t*; a book filled at the open of *t*+1 never holds the "
        "overnight move from the close of *t* to the open of *t*+1. Total returns, because residuals exist only close to close: "
        "ranking within the day removes a move common to every stock, but not the part of the market move that differs by beta, "
        "so compare the rows here with each other, not with phase 5's residual ICs.\n"
    )
    w = c.fill_ic.assign(cell=[f"{fmt(m, 4)} ({fmt(t, 1)})" for m, t in zip(c.fill_ic["mean"], c.fill_ic["t_stat"], strict=True)])
    w = w.pivot(index="window", columns="forecast", values="cell").reindex(index=ordered(c.fill_ic["window"]), columns=ordered(c.fill_ic["forecast"]))
    add(table(w.reset_index()))
    add("\nMean daily IC, t-statistic in brackets; the t-statistic treats days as independent, which overstates it for windows longer than a day.\n")

    add("## Slope rules\n")
    add(
        f"Development only, every path flat from {dev_first.date()} to {dev_last.date()}. Trailing: the phase 3 slope as it is "
        f"(these {c.reproduced} paths reproduce phase 5's log). Floored: never below zero. Expanding: estimated over every signal "
        "date since the start, the backtestable form of a slope fixed from development. Bar: t ≥ 2 and a deflated Sharpe "
        f"probability of at least 0.95, with the trials of phases 2 to 5 and the {c.trials_new} new paths here at each book size.\n"
    )
    if c.same:
        same = sorted(f"{o.name}, {money(o.book)}" for o in c.outcomes if key(o) in c.same)
        add("Identical to their trailing version, so not new trials: " + "; ".join(same) + ".\n")
    v = c.verdict.copy()
    m = {(o.forecast, o.label, o.book): o.metrics for o in c.outcomes}
    keys = list(zip(v["forecast"], v["rule"], v["book"], strict=True))
    v["gross %"] = [pct(m[k]["ann_gross_return"]) for k in keys]
    v["cost %"] = [pct(m[k]["ann_cost"]) for k in keys]
    v["turnover"] = [fmt(m[k]["turnover"], 3) for k in keys]
    v["capital"] = [fmt(m[k]["mean_exposure"], 2) for k in keys]
    v["book"] = v["book"].map(money)
    for col in ("net_sharpe", "t_stat", "benchmark_sharpe", "deflated_probability"):
        v[col] = v[col].map(lambda x: fmt(x, 2))
    cols = ["book", "forecast", "rule", "net_sharpe", "t_stat", "gross %", "cost %", "turnover", "capital", "deflated_probability", "trials", "clears"]
    add(table(v[cols]))
    add("")
    add(f"Experiment log: {len(log)} entries in `experiments.jsonl`.\n")
    text = "\n".join(out)
    (out_dir / "choice.md").write_text(text)
    return text


