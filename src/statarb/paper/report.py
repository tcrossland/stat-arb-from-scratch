PCT = 100.0
FILLS = {"close_t": "close of *t*", "open_t1": "open of *t*+1", "close_t1": "close of *t*+1"}   # engine fill timings, as the reports name them


def slug(name: str) -> str:
    return name.replace("model H=", "model_h").replace(" ", "_").replace(",", "")


def ordered(values) -> list:
    return list(dict.fromkeys(values))


