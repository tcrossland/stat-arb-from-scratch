"""Phase 4 report: reports/phase-04/portfolio.md and its charts.

Statistics only, no ticker's return on a date. Built from the runner's
outcomes in memory and, for the no-trade zone, phase 3's log. Imports nothing
from the runner (`statarb.portfolio.paths` says why).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from matplotlib.figure import Figure

from statarb.backtest.cost_report import money, pct
from statarb.backtest.engine import TRADING_DAYS
from statarb.backtest.metrics import by_year
from statarb.backtest.report import size_attribution
from statarb.factors.report import fmt, save_figure, table
from statarb.portfolio.paths import DECILE, HEADLINE, MODEL_NAMES

MAIN = (DECILE, f"{DECILE}, Model B", HEADLINE, MODEL_NAMES["pca"])


def _head(outcomes, head) -> list:
    return [o for o in outcomes if o.setting == head]


def _pick(outcomes, name: str, book: float, setting):
    return next(o for o in outcomes if o.name == name and o.book == book and o.setting == setting)


def _comparison_names(outcomes) -> tuple[str, str]:
    """The decile and optimiser names of the comparison signal's paths."""
    opt = next(o.name for o in outcomes if o.spec.group == "comparison")
    dec = next(o.name for o in outcomes if o.spec.group == "decile" and o.name.startswith(f"{DECILE}, ") and "Model B" not in o.name)
    return dec, opt


def _cumulative_chart(outcomes, head, books, names, path: Path) -> None:
    fig = Figure(figsize=(9, 3.6 * len(books)))
    axes = np.atleast_1d(fig.subplots(len(books), 1, sharex=True))
    for ax, book in zip(axes, books, strict=True):
        for name in names:
            d = _pick(outcomes, name, book, head).daily["net"]
            ax.plot(d.index, d.cumsum() * 100, lw=0.9, label=name)
        ax.axhline(0, color="grey", lw=0.5)
        ax.set_ylabel("cumulative net, % of capital")
        ax.set_title(f"{money(book)} of capital, headline cost model")
        ax.legend(fontsize=8)
    fig.tight_layout()
    save_figure(fig, path)


def _frontier_chart(outcomes, head, books, path: Path) -> None:
    fig = Figure(figsize=(9, 4.5))
    ax = fig.subplots()
    for book in books:
        for group, marker in (("cost multiplier", "o"), ("turnover budget", "s")):
            rows = [o for o in _head(outcomes, head) if o.book == book and (o.spec.group == group or o.spec.group == "headline")]
            rows = sorted(rows, key=lambda o: o.metrics["turnover"])
            ax.plot([o.metrics["turnover"] for o in rows], [o.metrics["sharpe"] for o in rows], marker=marker, lw=1,
                    label=f"{money(book)}, {'cost penalty' if group == 'cost multiplier' else 'turnover budget'}")
        d = _pick(outcomes, DECILE, book, head)
        ax.plot([d.metrics["turnover"]], [d.metrics["sharpe"]], marker="x", ms=9, ls="none", label=f"{money(book)}, decile sort")
    ax.axhline(0, color="grey", lw=0.5)
    ax.set_xlabel("turnover, capital traded per day")
    ax.set_ylabel("net Sharpe")
    ax.set_title("Net Sharpe against turnover, headline cost model")
    ax.legend(fontsize=8)
    fig.tight_layout()
    save_figure(fig, path)


def _results_row(o) -> list:
    m = o.metrics
    return [
        money(o.book), o.name, fmt(m["sharpe"], 2), pct(m["ann_return"]), pct(m["ann_vol"]), pct(m["ann_gross_return"]),
        fmt(m["gross_sharpe"], 2), pct(m["ann_cost"]), pct(m["ann_cost_commission"]), pct(m["ann_cost_impact"]), pct(m["ann_borrow"]),
        fmt(m["turnover"], 3), fmt(m["mean_exposure"], 2), f"{m['median_names']:.0f}", pct(m["max_drawdown"]),
    ]


RESULT_COLUMNS = [
    "book", "configuration", "net Sharpe", "net %", "vol %", "gross %", "gross Sharpe", "cost %", "commission %",
    "impact %", "borrow %", "turnover", "capital", "names", "max drawdown %",
]


def _zone_entry(phase_3_log: list[dict], variant: str, book: float, spread: float) -> dict | None:
    found = [
        e for e in phase_3_log
        if e["config"].get("name") == variant and e["config"].get("no_trade_zone") and e["config"].get("book_size") == book
        and e["config"].get("spread") == spread
    ]
    return found[-1]["metrics"] if found else None


def write_report(plab, outcomes, verdict: pd.DataFrame, phase_3_log: list[dict], log: list[dict], out_dir: Path) -> str:
    out_dir.mkdir(parents=True, exist_ok=True)
    pc, lab = plab.pc, plab.lab
    head = plab.head_setting()
    books = pc.run.book_sizes
    h, o_ = pc.headline, pc.optimiser
    comp_decile, comp_opt = _comparison_names(outcomes)
    lines = [
        "# Phase 4: portfolio construction",
        "",
        "Generated by `uv run python -m statarb.portfolio.run` from `config/portfolio.toml`, with the phase 3 cost model",
        f"(`config/costs.toml`) and its `{pc.run.variant}` signal, unchanged; the `{pc.run.comparison}` signal runs beside it",
        f"through the decile sort and the headline optimiser. Fills at `{pc.run.fill}`. Signals from {lab.cfg.period.start} to",
        f"{lab.tables.dates[-1].date()}. Returns are per dollar of capital, as in phase 3; days before a path's expected",
        "move exists count, with an empty book.",
        "",
        f"The optimiser maximises the expected {o_.horizon_days}-day move less λ·{o_.horizon_days}·w′Σw less κ times the phase 3",
        f"cost of the trade, dollar neutral, with each risk factor's exposure within {o_.factor_tolerance:.0%} of capital, each",
        f"name within {o_.position_cap:.0%} of capital and {o_.adv_cap:.0%} of its average dollar volume, and gross at most",
        f"{o_.gross_cap:g} times capital. Headline: λ = {h.risk_aversion:g}, κ = {h.cost_multiplier:g}, no turnover budget,",
        f"minimum trade ${h.min_trade_dollars:,.0f}, {'with' if h.re_solve else 'no'} re-solve, {MODEL_NAMES[pc.risk.model]} signal and risk.",
        "The decile sort is the phase 3 path at the same cost.",
        "",
        "## Decile sort against optimiser",
        "",
    ]
    names = [*MAIN, comp_decile, comp_opt]
    rows = [_results_row(_pick(outcomes, n, b, head)) for b in books for n in names]
    lines += [
        table(pd.DataFrame(rows, columns=RESULT_COLUMNS)),
        "",
        "Turnover is capital traded per day; capital is the mean gross exposure per dollar of capital; names is the",
        "median number held. Cost and borrow are % of capital a year.",
        "",
        "![Cumulative net return](cumulative_net.png)",
        "",
    ]
    _cumulative_chart(outcomes, head, books, [DECILE, HEADLINE, MODEL_NAMES["pca"], comp_opt], out_dir / "cumulative_net.png")

    # By year.
    year_cols, year_data = [], {}
    for b in books:
        for n in (DECILE, HEADLINE, comp_opt, MODEL_NAMES["pca"]):
            y = by_year(_pick(outcomes, n, b, head).daily)
            col = f"{money(b)} {n}"
            year_cols.append(col)
            year_data[col] = y["net_return"]
    years = sorted(set().union(*(s.index for s in year_data.values())))
    year_rows = [[y, *[pct(year_data[c].get(y, np.nan)) for c in year_cols]] for y in years]
    lines += [
        "## Net return by year",
        "",
        "Net return on capital in each calendar year, %.",
        "",
        table(pd.DataFrame(year_rows, columns=["year", *year_cols])),
        "",
    ]

    # Exposure.
    exp_rows = []
    for b in books:
        for o in _head(outcomes, head):
            if o.book != b or not (o.spec.group in ("decile", "headline", "models", "comparison", "re-solve") or o.spec.name.startswith("minimum")):
                continue
            m = o.metrics
            exp_rows.append([
                money(b), o.name, fmt(m["beta_mean"], 3), fmt(m["beta_sd"], 3), fmt(m["sector_abs_mean"], 3), fmt(m["sector_abs_sd"], 3),
                pct(m["fitted_ann"]), pct(m["fitted_vol"]), pct(m["ann_vol"]), fmt(m["net_dollar_imbalance"], 4),
            ])
    lines += [
        "## Realised factor exposure",
        "",
        "Against Model A for every path: the book's net market beta, the sum of its absolute net exposures to the",
        "sector factors, both per dollar of capital and measured on the holdings carried into each day, and the",
        "annual P&L and volatility of the fitted (market and sector) part of the held stocks' returns, % of capital.",
        "Total volatility and the mean net dollar imbalance (as a share of gross) beside them.",
        "",
        table(pd.DataFrame(exp_rows, columns=[
            "book", "configuration", "beta mean", "beta sd", "sector exposure mean", "sector exposure sd",
            "fitted P&L %", "fitted vol %", "total vol %", "dollar imbalance"])),
        "",
    ]

    # Models.
    model_rows = []
    for b in books:
        for o in _head(outcomes, head):
            if o.book == b and (o.spec.group in ("models", "headline") or (o.spec.group == "decile" and o.spec.variant == pc.run.variant)):
                m = o.metrics
                model_rows.append([
                    money(b), o.name, MODEL_NAMES[o.spec.residuals], "" if o.spec.risk is None else MODEL_NAMES[o.spec.risk],
                    fmt(m["sharpe"], 2), pct(m["ann_gross_return"]), fmt(m["gross_sharpe"], 2), pct(m["ann_cost"]), fmt(m["turnover"], 3),
                ])
    lines += [
        "## Model A and Model B",
        "",
        "Each model's residuals as the signal's input and each as the optimiser's risk model, at the headline",
        "settings, with the decile sort on each model's residuals. Model B's residuals and diagnostics are compared",
        "with Model A's in [`model_b.md`](model_b.md).",
        "",
        table(pd.DataFrame(model_rows, columns=["book", "configuration", "signal on", "risk model", "net Sharpe", "gross %", "gross Sharpe", "cost %", "turnover"])),
        "",
    ]
    size_cols = {}
    for n in (DECILE, f"{DECILE}, Model B"):
        o = _pick(outcomes, n, books[0], head)
        size_cols[n] = size_attribution(plab.labs[o.spec.residuals].tables, lab.cfg, o)
    buckets = sorted(set().union(*(s.index for s in size_cols.values())))
    lines += [
        "### Decile P&L by size",
        "",
        "Annual gross P&L per dollar of gross, %, by quintile of trailing 60-day median dollar volume among members",
        "on the day before the P&L (1 = smallest), as in phase 2's report. The decile sort's positions do not depend",
        "on the book size.",
        "",
        table(pd.DataFrame([[int(k), *[pct(size_cols[n].get(k, np.nan)) for n in size_cols]] for k in buckets],
                           columns=["bucket", "on Model A residuals", "on Model B residuals"])),
        "",
    ]

    # The no-trade zone.
    zone_rows = []
    for b in books:
        for variant, opt_name in ((pc.run.variant, HEADLINE), (pc.run.comparison, comp_opt)):
            z = _zone_entry(phase_3_log, variant, b, head.spread)
            o = _pick(outcomes, opt_name, b, head).metrics
            if z is not None:
                zone_rows.append([money(b), f"{variant}, no-trade zone (phase 3)", fmt(z["sharpe"], 2), pct(z["ann_return"]),
                                  pct(z["ann_gross_return"]), fmt(z["turnover"], 3), fmt(z["mean_exposure"], 2), fmt(z["net_dollar_imbalance"], 3)])
            zone_rows.append([money(b), opt_name, fmt(o["sharpe"], 2), pct(o["ann_return"]), pct(o["ann_gross_return"]),
                              fmt(o["turnover"], 3), fmt(o["mean_exposure"], 2), fmt(o["net_dollar_imbalance"], 3)])
    lines += [
        "## Against the no-trade zone",
        "",
        "Phase 3's no-trade zone on the same signal, book size and headline cost, read from its log, beside the",
        "optimiser on the same signal. The dollar imbalance is the mean net dollar exposure as a share of gross.",
        "",
        table(pd.DataFrame(zone_rows, columns=["book", "configuration", "net Sharpe", "net %", "gross %", "turnover", "capital", "dollar imbalance"])),
        "",
    ]

    # Sensitivity.
    sens_rows = []
    for b in books:
        for o in _head(outcomes, head):
            if o.book != b or o.spec.is_decile:
                continue
            m = o.metrics
            sens_rows.append([money(b), o.name, fmt(m["sharpe"], 2), pct(m["ann_return"]), pct(m["ann_gross_return"]), pct(m["ann_cost"]),
                              fmt(m["turnover"], 3), fmt(m["mean_exposure"], 2), f"{m['median_names']:.0f}", pct(m["ex_ante_vol"])])
    lines += [
        "## Sensitivity",
        "",
        "Each optimiser path differs from the headline in one respect. All at the headline cost model.",
        "",
        table(pd.DataFrame(sens_rows, columns=["book", "configuration", "net Sharpe", "net %", "gross %", "cost %", "turnover", "capital", "names", "ex-ante vol %"])),
        "",
    ]

    # Matched turnover.
    match_rows = []
    for b in books:
        rows_b = [o for o in _head(outcomes, head) if o.book == b and o.spec.group in ("headline", "cost multiplier", "turnover budget")]
        for o in sorted(rows_b, key=lambda o: o.metrics["turnover"]):
            m = o.metrics
            kind = "turnover budget" if o.spec.group == "turnover budget" else "cost penalty"
            per_turn = m["ann_gross_return"] / (m["turnover"] * TRADING_DAYS) * 1e4 if m["turnover"] > 0 else np.nan
            match_rows.append([money(b), kind, o.name, fmt(m["turnover"], 3), pct(m["ann_gross_return"]), fmt(per_turn, 2), fmt(m["sharpe"], 2)])
    lines += [
        "## Cost penalty against turnover budget",
        "",
        "Paths ordered by turnover at each book size. Gross per dollar traded is the gross return over the capital",
        "traded, in bps: what a dollar of trading earns before costs.",
        "",
        table(pd.DataFrame(match_rows, columns=["book", "control", "configuration", "turnover", "gross %", "gross bps per dollar traded", "net Sharpe"])),
        "",
        "![Net Sharpe against turnover](turnover_frontier.png)",
        "",
    ]
    _frontier_chart(outcomes, head, books, out_dir / "turnover_frontier.png")

    # Minimum trade and re-solve.
    min_rows = []
    for b in books:
        for o in _head(outcomes, head):
            if o.book != b or not (o.spec.group in ("headline", "minimum trade", "re-solve")):
                continue
            m = o.metrics
            min_rows.append([
                money(b), o.name, fmt(m["sharpe"], 2), pct(m["ann_cost_commission"]), fmt(m["turnover"], 3), fmt(m["mean_exposure"], 2),
                fmt(m["trades_per_day"], 1), fmt(m["dropped_per_day"], 1), fmt(m["dollar_breach_max"], 4), f"{m['dollar_breach_material_days']}",
                fmt(m["factor_breach_max"], 4), f"{m['factor_breach_material_days']}", fmt(m["re_solve_rounds_mean"], 2), f"{m['re_solve_failed_days']}",
            ])
    lines += [
        "## Minimum trade size and the re-solve",
        "",
        "Breaches are of dollar and factor neutrality after the filter, beyond the tolerances, as a fraction of",
        "capital, at decision prices; breach days count those above 0.1% of capital. The re-solve holds the names",
        f"whose trades were dropped and solves again over the rest, up to {o_.re_solve_rounds} times a day; a failed re-solve",
        "keeps the last filtered book.",
        "",
        table(pd.DataFrame(min_rows, columns=[
            "book", "configuration", "net Sharpe", "commission %", "turnover", "capital", "trades/day", "dropped/day",
            "max dollar breach", "dollar breach days", "max factor breach", "factor breach days", "re-solves/day", "failed re-solves"])),
        "",
    ]

    # Spread bracket.
    settings = sorted({o.setting for o in outcomes}, key=lambda s: s.spread)
    spreads = [s.spread for s in settings]
    bracketed_names = list(dict.fromkeys(o.name for o in outcomes if o.setting != head))
    br_rows = [[money(b), n, *[fmt(_pick(outcomes, n, b, s).metrics["sharpe"], 2) for s in settings]] for b in books for n in bracketed_names]
    lines += [
        "## Spread bracket",
        "",
        "Paths optimised under the headline cost, re-costed at each half-spread of the phase 3 bracket without",
        "re-optimising: net Sharpe.",
        "",
        table(pd.DataFrame(br_rows, columns=["book", "configuration", *[f"{s:g} bps" for s in spreads]])),
        "",
    ]

    # Solver.
    solver_rows = []
    for o in _head(outcomes, head):
        if o.spec.is_decile:
            continue
        m = o.metrics
        solver_rows.append([money(o.book), o.name, m["solver_days"], m["idle_days"], m["failed_days"]])
    lines += [
        "## Solver",
        "",
        "Decision days from the first signal date. Idle days have no eligible names (before the expected move",
        "exists) and the book is empty. Failed days are those on which the solver did not return an optimal",
        "solution, so the previous book was held. Solve times are wall-clock and vary between runs, so they are",
        "in `docs/requirements.md`, not here.",
        "",
        table(pd.DataFrame(solver_rows, columns=["book", "configuration", "days", "idle", "failed"])),
        "",
    ]

    # The bar.
    v = verdict.assign(
        book=verdict["book"].map(money),
        net_sharpe=verdict["net_sharpe"].map(lambda x: fmt(x, 2)),
        t_stat=verdict["t_stat"].map(lambda x: fmt(x, 2)),
        benchmark_sharpe=verdict["benchmark_sharpe"].map(lambda x: fmt(x, 2)),
        deflated_probability=verdict["deflated_probability"].map(lambda x: fmt(x, 3)),
    )
    lines += [
        "## Against the bar",
        "",
        "A net edge needs t ≥ 2 on daily net returns and a deflated Sharpe probability of at least 0.95, against",
        "every position path in the repository's logs up to this phase. Each optimiser setting is one trial across",
        "book sizes, like phase 3's no-trade paths; the spread bracket adds none.",
        "",
        table(v),
        "",
        f"Experiment log: {len(log)} entries in `experiments.jsonl`.",
        "",
    ]
    text = "\n".join(lines)
    (out_dir / "portfolio.md").write_text(text)
    return text

