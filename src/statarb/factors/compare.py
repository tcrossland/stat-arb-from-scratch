"""Model B against Model A: reports/phase-04/model_b.md and its chart.

The phase 1 diagnostics, run on both models' residuals over the rows they
share: universe members on the day a pair starts, from Model B's first
residual date. Statistics only, no ticker's return on a date.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
from matplotlib.figure import Figure

from statarb.data.schema import DATE, TICKER
from statarb.factors.report import (
    MIN_CORR_DAYS,
    SIZE_WINDOW,
    Report,
    average_pairwise_correlation,
    daily_rank_correlation,
    fmt,
    lead,
    size_bucket,
    summarise,
    table,
)

MODELS = {"a": "Model A", "b": "Model B"}


def shared_rows(res_a: pd.DataFrame, res_b: pd.DataFrame) -> pd.DataFrame:
    """(date, ticker) rows with a residual under both models: `ret`, `res_a` and `res_b`."""
    a = res_a[[DATE, TICKER, "ret", "residual"]].rename(columns={"residual": "res_a"})
    b = res_b[[DATE, TICKER, "residual"]].rename(columns={"residual": "res_b"})
    both = a.merge(b, on=[DATE, TICKER], how="inner", validate="one_to_one")
    return both.sort_values([DATE, TICKER], kind="mergesort").reset_index(drop=True)


def _pairwise_by_year(members: pd.DataFrame, rows: pd.DataFrame) -> pd.DataFrame:
    """Average pairwise correlation of raw returns and each model's residuals, as in the phase 1 report."""
    out = []
    for year, grp in members.groupby("year"):
        days = grp[DATE].nunique()
        if days < MIN_CORR_DAYS:
            continue
        steady = grp.groupby(TICKER)[DATE].count()
        tickers = steady[steady >= 0.9 * days].index
        sub = rows[(rows[DATE].dt.year == year) & rows[TICKER].isin(tickers)]
        cells = [year, len(tickers)]
        for col in ("ret", "res_a", "res_b"):
            cells.append(average_pairwise_correlation(sub.pivot(index=DATE, columns=TICKER, values=col)))
        out.append(cells)
    return pd.DataFrame(out, columns=["year", "stocks", "raw", "res_a", "res_b"])


def _lag(grp: pd.DataFrame, col: str, k: int) -> dict[str, float]:
    return summarise(daily_rank_correlation(grp[col], grp[f"{col}_lead{k}"], [grp[DATE]]))


def compare_models(res_a: pd.DataFrame, res_b: pd.DataFrame, universe: pd.DataFrame, prices: pd.DataFrame, cfg: dict) -> Report:
    """The comparison report's markdown and chart. `cfg` is `[report]` of config/factors.toml."""
    rows = shared_rows(res_a, res_b)
    calendar = pd.DatetimeIndex(sorted(rows[DATE].unique()))
    rows = rows.merge(universe[[DATE, TICKER]].assign(member=True), on=[DATE, TICKER], how="left")
    rows["member"] = rows["member"].fillna(False).astype(bool)
    members = rows[rows["member"]].copy()
    lags = range(1, cfg["autocorrelation_lags"] + 1)
    for col in ("res_a", "res_b"):
        for k in lags:
            members[f"{col}_lead{k}"] = lead(rows, col, k, calendar).reindex(members.index)
    members["year"] = members[DATE].dt.year
    members["size"] = size_bucket(members, prices, calendar, cfg["size_buckets"]).astype("Int64")

    out = ["# Phase 4: Model B against Model A", ""]
    out += [
        "Generated by `uv run python -m statarb.factors.build --model pca`. Model B: the top 15 principal",
        "components of standardised returns over the 252 days ending *t−1* (Avellaneda and Lee 2010, section 2.1).",
        "Model A: the market and sector ETF regression of phase 1. Statistics use universe members on the day a",
        "pair starts, over the rows where both models have a residual. Daily rank correlation is the Spearman",
        "correlation across stocks on one day, averaged over days; the t-statistic treats days as independent.",
        "",
        "## Coverage",
        "",
        f"- Model B residual rows: {len(res_b):,} for {res_b[TICKER].nunique()} stocks, {res_b[DATE].min().date()} to {res_b[DATE].max().date()}.",
        f"- Rows with both residuals: {len(rows):,}, of which universe members {len(members):,}.",
        "",
        "## Residual size and overlap",
        "",
        "Over member rows: the standard deviation of each residual, the share of the variance of daily returns",
        "it leaves unexplained, and the correlation between the two models' residuals.",
        "",
    ]
    var_ret = members["ret"].var()
    size_rows = [
        (MODELS[m], fmt(members[f"res_{m}"].std(), 4), fmt(members[f"res_{m}"].var() / var_ret, 3)) for m in ("a", "b")
    ]
    out += [
        table(pd.DataFrame(size_rows, columns=["model", "residual std", "variance share of returns"])),
        "",
        f"Correlation of Model A and Model B residuals: {members['res_a'].corr(members['res_b']):.3f}.",
        "",
    ]

    corr = _pairwise_by_year(members, rows)
    out += [
        "## Average pairwise correlation",
        "",
        "Stocks in the universe on at least 90% of the year's days with both residuals; correlations of daily",
        f"values within the year, averaged over all pairs. Years with fewer than {MIN_CORR_DAYS} such days are left out.",
        "",
        table(pd.DataFrame({
            "year": corr.year, "stocks": corr.stocks, "raw": corr.raw.map(fmt),
            "Model A": corr.res_a.map(fmt), "Model B": corr.res_b.map(fmt)})),
        "",
        f"Mean over years: raw {corr.raw.mean():.3f}, Model A {corr.res_a.mean():.3f}, Model B {corr.res_b.mean():.3f}.",
        "",
    ]

    lag_rows = []
    for k in lags:
        a, b = _lag(members, "res_a", k), _lag(members, "res_b", k)
        lag_rows.append((k, fmt(a["mean"], 4), fmt(a["t"], 1), fmt(b["mean"], 4), fmt(b["t"], 1)))
    out += [
        "## Residual autocorrelation",
        "",
        "Daily rank correlation of a residual with the same stock's residual *k* days later: what a reversal",
        "signal trades.",
        "",
        table(pd.DataFrame(lag_rows, columns=["lag", "Model A mean", "Model A t", "Model B mean", "Model B t"])),
        "",
    ]

    yearly = []
    for year, grp in members.groupby("year"):
        a, b = _lag(grp, "res_a", 1), _lag(grp, "res_b", 1)
        yearly.append((year, a["mean"], a["t"], b["mean"], b["t"]))
    yearly_frame = pd.DataFrame(yearly, columns=["year", "a", "ta", "b", "tb"])
    fig = Figure(figsize=(9, 3.5))
    ax = fig.subplots()
    x = np.arange(len(yearly_frame))
    ax.bar(x - 0.2, [float(fmt(v, 4) or "nan") for v in yearly_frame.a], 0.4, label="Model A")
    ax.bar(x + 0.2, [float(fmt(v, 4) or "nan") for v in yearly_frame.b], 0.4, label="Model B")
    ax.set_xticks(x, [str(y) for y in yearly_frame.year])
    ax.axhline(0, color="grey", lw=0.8)
    ax.set_title("Lag-1 residual daily rank autocorrelation by year")
    ax.legend(fontsize=8)
    out += [
        "### By year (lag 1)",
        "",
        "![Lag-1 by year](autocorrelation_by_year_ab.png)",
        "",
        table(pd.DataFrame({
            "year": yearly_frame.year, "Model A mean": yearly_frame.a.map(lambda v: fmt(v, 4)),
            "Model A t": yearly_frame.ta.map(lambda v: fmt(v, 1)), "Model B mean": yearly_frame.b.map(lambda v: fmt(v, 4)),
            "Model B t": yearly_frame.tb.map(lambda v: fmt(v, 1))})),
        "",
    ]

    size_table = []
    for bucket, grp in members.dropna(subset=["size"]).groupby("size"):
        a, b = _lag(grp, "res_a", 1), _lag(grp, "res_b", 1)
        size_table.append((int(bucket), fmt(a["mean"], 4), fmt(a["t"], 1), fmt(b["mean"], 4), fmt(b["t"], 1)))
    out += [
        "### By size (lag 1)",
        "",
        (
            f"Buckets of trailing {SIZE_WINDOW}-day median dollar volume among members each day, 1 = smallest."
            " Sector ETFs hold the largest names, which understates their Model A residuals; Model B's factors"
            " come from the universe itself."
        ),
        "",
        table(pd.DataFrame(size_table, columns=["bucket", "Model A mean", "Model A t", "Model B mean", "Model B t"])),
        "",
    ]
    return Report(text="\n".join(out) + "\n", figures={"autocorrelation_by_year_ab.png": fig})
