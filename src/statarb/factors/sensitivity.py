"""Sensitivity of Model A to the estimation window.

    uv run python -m statarb.factors.sensitivity

Runs Model A at several window lengths, each with the minimum history at the
same share of the window as config/factors.toml, and compares them on the
universe member-days where every window has a residual. Writes
reports/phase-01/window_sensitivity.md. Nothing here feeds later phases.
"""

from __future__ import annotations

import argparse
import sys
from typing import Any

import numpy as np
import pandas as pd

from statarb.config import load_config, repo_root, resolve_path
from statarb.data.schema import DATE, TICKER
from statarb.factors.build import build_residuals, stocks_to_model
from statarb.factors.report import (
    MIN_CORR_DAYS,
    average_pairwise_correlation,
    daily_rank_correlation,
    fmt,
    lead,
    summarise,
    table,
)
from statarb.io import read_parquet

WINDOWS = (60, 126, 252)


def compare_windows(
    returns: pd.DataFrame,
    sectors: pd.DataFrame,
    prices: pd.DataFrame,
    universe: pd.DataFrame,
    stocks: list[str],
    factors_cfg: dict[str, Any],
    market: str,
    windows: tuple[int, ...] = WINDOWS,
) -> pd.DataFrame:
    """One row per window; `attrs` holds the common rows' count and first date."""
    share = factors_cfg["model"]["min_observations"] / factors_cfg["model"]["window_days"]
    runs = {}
    for window in windows:
        model = {**factors_cfg["model"], "window_days": window, "min_observations": int(np.ceil(share * window))}
        runs[window] = build_residuals(returns, sectors, prices, stocks, {**factors_cfg, "model": model}, market)

    keys = universe[[DATE, TICKER]]
    for res in runs.values():
        keys = keys.merge(res[[DATE, TICKER]], on=[DATE, TICKER])
    rows = []
    daily = {}
    for window, res in runs.items():
        calendar = pd.DatetimeIndex(sorted(res[DATE].unique()))
        res = res.assign(lead1=lead(res, "residual", 1, calendar).to_numpy())
        common = keys.merge(res, on=[DATE, TICKER], how="left")
        daily[window] = daily_rank_correlation(common["residual"], common["lead1"], [common[DATE]])
        ac = summarise(daily[window])
        years = [
            average_pairwise_correlation(grp.pivot(index=DATE, columns=TICKER, values="residual"))
            for _, grp in common.groupby(common[DATE].dt.year)
            if grp[DATE].nunique() >= MIN_CORR_DAYS
        ]
        ordered = res.sort_values([TICKER, DATE], kind="mergesort")
        step = ordered.groupby(TICKER)["beta_market"].diff().abs()
        rows.append(
            {
                "window": window,
                "min obs": int(np.ceil(share * window)),
                "first residual": res[DATE].min().date(),
                "residual std": fmt(common["residual"].std(), 4),
                "pairwise corr": fmt(float(np.mean(years)), 4),
                "lag-1 rank mean": fmt(ac["mean"], 4),
                "lag-1 t": fmt(ac["t"], 1),
                "beta_market daily change": fmt(step.median(), 4),
                "market-only share": f"{common['market_only'].mean():.1%}",
            }
        )
    out = pd.DataFrame(rows)
    reference = max(windows)
    paired = []
    for window in windows:
        if window == reference:
            paired.append("")
            continue
        s = summarise((daily[window] - daily[reference]).dropna())
        paired.append(f"{s['mean']:+.4f} (t {s['t']:.1f})")
    out.insert(out.columns.get_loc("lag-1 t") + 1, f"lag-1 minus {reference}-day", paired)
    out.attrs["rows"] = len(keys)
    out.attrs["start"] = keys[DATE].min().date()
    return out


def render(result: pd.DataFrame) -> str:
    """window_sensitivity.md from compare_windows' result."""
    return "\n".join(
        [
            "# Phase 1: estimation window sensitivity",
            "",
            "Generated by `uv run python -m statarb.factors.sensitivity`. Model A at each window, with the minimum",
            "history at the same share of the window as `config/factors.toml`. All statistics except the first",
            f"residual date use the {result.attrs['rows']:,} universe member-days where every window has a residual,",
            f"from {result.attrs['start']}.",
            "",
            "- residual std: standard deviation of residuals.",
            "- pairwise corr: average pairwise correlation of residuals, by year, averaged over years.",
            "- lag-1 rank: daily cross-sectional rank correlation of residuals on *t* and *t+1*. The paired",
            "  column is the mean daily difference from the longest window, with its t-statistic.",
            "- beta_market daily change: median absolute day-to-day change in a stock's market beta, a measure",
            "  of estimation noise.",
            "",
            table(result),
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args(argv)
    root = repo_root()
    data_cfg = load_config("data", root)
    factors_cfg = load_config("factors", root)
    processed = resolve_path(data_cfg["paths"]["processed"], root)
    returns = read_parquet(processed / "returns.parquet")
    result = compare_windows(
        returns,
        read_parquet(processed / "sectors.parquet"),
        read_parquet(processed / "prices.parquet"),
        read_parquet(processed / "universe.parquet"),
        stocks_to_model(read_parquet(processed / "candidates.parquet"), returns),
        factors_cfg,
        data_cfg["factors"]["market"],
    )
    text = render(result)
    out = resolve_path(data_cfg["paths"]["reports"], root) / "phase-01" / "window_sensitivity.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
